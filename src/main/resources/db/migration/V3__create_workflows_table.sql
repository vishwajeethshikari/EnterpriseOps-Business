
CREATE TABLE workflows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    workflow_number VARCHAR(50) NOT NULL UNIQUE,
    order_number VARCHAR(50) NOT NULL,
    workflow_type VARCHAR(50) NOT NULL DEFAULT 'SUPPORT_TICKET',

    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_APPROVAL',

    proposed_issue_description TEXT NOT NULL,
    proposed_priority VARCHAR(20) NOT NULL DEFAULT 'MEDIUM',

    approval_decision VARCHAR(20),
    approved_by VARCHAR(100),
    approval_reason TEXT,
    approved_at TIMESTAMP,

    ticket_number VARCHAR(50),
    failure_reason TEXT,

    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_workflow_order
        FOREIGN KEY (order_number)
        REFERENCES orders(order_number),

    CONSTRAINT fk_workflow_ticket
        FOREIGN KEY (ticket_number)
        REFERENCES support_tickets(ticket_number),

    CONSTRAINT chk_workflow_status
        CHECK (
            status IN (
                'PENDING_APPROVAL',
                'APPROVED',
                'REJECTED',
                'COMPLETED',
                'FAILED'
            )
        ),

    CONSTRAINT chk_workflow_priority
        CHECK (proposed_priority IN ('LOW', 'MEDIUM', 'HIGH')),

    CONSTRAINT chk_workflow_decision
        CHECK (
            approval_decision IS NULL
            OR approval_decision IN ('APPROVED', 'REJECTED')
        )
);

CREATE INDEX idx_workflows_order_number
    ON workflows(order_number);

CREATE INDEX idx_workflows_status
    ON workflows(status);
